/**
 * Generates minute-by-minute actigraph data points for a 24-hour cycle
 * for a specific patient, matching circadian biology.
 */
export function generate24HourActigraphWave(patient: PatientRecord): ActigraphDataPoint[] {
  const points: ActigraphDataPoint[] = [];
  const isCondition = patient.group === 'condition';
  
  // 1440 minutes in a day (sample every 15 minutes for smooth responsive chart = 96 intervals)
  for (let interval = 0; interval < 96; interval++) {
    const minute = interval * 15;
    const hour = Math.floor(minute / 60);
    const minRemainder = minute % 60;
    const timestamp = `${hour.toString().padStart(2, '0')}:${minRemainder.toString().padStart(2, '0')}`;
    const isNight = hour >= 23 || hour < 7;
    
    // Circadian biological wave formula:
    // Peak activity ~ 11:00 to 14:00 and 17:00 to 19:00
    // Trough activity ~ 02:00 to 05:00
    const timeAngle = ((hour + minRemainder / 60) / 24) * 2 * Math.PI - 1.5;
    const circadianSine = Math.sin(timeAngle);
    
    // Pseudo noise based on patient ID and minute
    const pseudoRand = Math.sin(minute * 12.9898 + patient.ageNumeric * 78.233) * 43758.5453;
    const noise = (pseudoRand - Math.floor(pseudoRand)) - 0.5;

    let baseVal = 0;
    if (isCondition) {
      // Condition: Depressed patients have flattened circadian amplitude (lower peak during day),
      // disrupted sleep (frequent night awakenings/micro-spikes), and psychomotor retardation.
      if (isNight) {
        // Sleep disturbances, insomnia spikes
        baseVal = 60 + Math.max(0, noise * 120);
        if (interval % 12 === 0) baseVal += 140; // nocturnal restlessness
      } else {
        // Blunted daytime peak
        baseVal = 200 + (circadianSine * 110) + (noise * 90);
      }
    } else {
      // Healthy control: Robust circadian amplitude, sharp daytime peaks, near-zero deep nocturnal rest
      if (isNight) {
        baseVal = Math.max(5, 18 + noise * 25);
      } else {
        baseVal = 440 + (circadianSine * 240) + (noise * 180);
        // Morning waking boost (8-10am)
        if (hour >= 8 && hour <= 10) baseVal += 90;
        // Evening commute/exercise boost (17-19pm)
        if (hour >= 17 && hour <= 19) baseVal += 80;
      }
    }

    const activity = Math.max(0, Math.round(baseVal));
    points.push({
      minute,
      timestamp,
      activity,
      smoothed: Math.max(0, Math.round(baseVal * 0.92)),
      isNight
    });
  }

  return points;
}
